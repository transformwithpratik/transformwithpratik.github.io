// Builds supabase/seed/content.sql from the recipe, exercise, food and resource sources.
// Usage: node scripts/content/build-seed.mjs
// Re-running is safe: rows are inserted with ON CONFLICT DO NOTHING, so edits made in the
// admin dashboard are never overwritten.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { INGREDIENTS, macrosFor } from './ingredients.mjs';
import { RECIPES } from './recipes.mjs';
import { EXERCISES } from './exercises.mjs';
import { RESOURCES } from './resources.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

// Reference foods for quick logging (per serving, derived from the same per-100 g table).
const FOODS = [
  ['Cooked white rice', 'grains', '1 cup cooked (150 g)', 150, [130, 2.7, 28.2, 0.3]],
  ['Roti (no ghee)', 'grains', '1 medium roti (30 g atta)', 30, INGREDIENTS.atta.per100],
  ['Rolled oats', 'grains', '40 g dry', 40, INGREDIENTS.oats.per100],
  ['Poha (dry)', 'grains', '50 g dry', 50, INGREDIENTS.poha.per100],
  ['Whole wheat bread', 'grains', '1 slice (28 g)', 28, INGREDIENTS.bread_ww.per100],
  ['Moong dal (dry weight)', 'pulses', '30 g dry (1 katori cooked)', 30, INGREDIENTS.moong_dal.per100],
  ['Masoor dal (dry weight)', 'pulses', '30 g dry (1 katori cooked)', 30, INGREDIENTS.masoor_dal.per100],
  ['Boiled chickpeas', 'pulses', '1 cup (150 g)', 150, INGREDIENTS.chana_cooked.per100],
  ['Cooked rajma', 'pulses', '1 katori (150 g)', 150, [127, 8.7, 22.8, 0.5]],
  ['Soya chunks (dry weight)', 'protein', '30 g dry', 30, INGREDIENTS.soya_chunks.per100],
  ['Paneer', 'protein', '100 g', 100, INGREDIENTS.paneer.per100],
  ['Firm tofu', 'protein', '100 g', 100, INGREDIENTS.tofu.per100],
  ['Whey protein', 'protein', '1 scoop (30 g)', 30, INGREDIENTS.whey.per100],
  ['Whole egg', 'protein', '1 large egg (50 g)', 50, INGREDIENTS.egg.per100],
  ['Egg white', 'protein', '1 egg white (33 g)', 33, INGREDIENTS.egg_white.per100],
  ['Curd (whole milk)', 'dairy', '1 katori (150 g)', 150, INGREDIENTS.curd.per100],
  ['Hung curd / Greek yogurt', 'dairy', '100 g', 100, INGREDIENTS.hung_curd.per100],
  ['Toned milk', 'dairy', '1 glass (250 ml)', 250, INGREDIENTS.toned_milk.per100],
  ['Peanuts', 'nuts', '30 g (a small handful)', 30, INGREDIENTS.peanuts.per100],
  ['Almonds', 'nuts', '10 almonds (14 g)', 14, INGREDIENTS.almonds.per100],
  ['Peanut butter', 'nuts', '1 tbsp (16 g)', 16, INGREDIENTS.peanut_butter.per100],
  ['Makhana', 'snacks', '30 g', 30, INGREDIENTS.makhana.per100],
  ['Banana', 'fruit', '1 medium (100 g edible)', 100, INGREDIENTS.banana.per100],
  ['Apple', 'fruit', '1 medium (150 g)', 150, INGREDIENTS.apple.per100],
  ['Ghee', 'fats', '1 tsp (5 g)', 5, INGREDIENTS.ghee.per100],
  ['Cooking oil', 'fats', '1 tsp (5 g)', 5, INGREDIENTS.oil.per100],
];

const lines = [];
lines.push('-- Generated by scripts/content/build-seed.mjs. Do not edit by hand.');
lines.push('-- Macros are estimates calculated from per-100 g food composition values (USDA FoodData Central, IFCT 2017, pack labels).');
lines.push('');

const report = [];
RECIPES.forEach((r, i) => {
  const m = macrosFor(r.ingredients, r.servings);
  report.push(`${r.slug.padEnd(30)} ${String(m.calories).padStart(4)} kcal  P ${String(m.protein_g).padStart(5)}  C ${String(m.carbs_g).padStart(5)}  F ${String(m.fat_g).padStart(5)}`);
  const ingredients = r.ingredients.map((x) => ({ item: x.label, grams: x.g || null }));
  lines.push(`insert into public.recipes (slug, title, summary, servings, prep_minutes, cook_minutes, calories, protein_g, carbs_g, fat_g, ingredients, steps, categories, diet_tags, tips, sort_order)
values (${q(r.slug)}, ${q(r.title)}, ${q(r.summary)}, ${r.servings}, ${r.prep}, ${r.cook}, ${m.calories}, ${m.protein_g}, ${m.carbs_g}, ${m.fat_g}, ${json(ingredients)}, ${json(r.steps)}, ${arr(r.categories)}, ${arr(r.diet)}, ${q(r.tips)}, ${i})
on conflict (slug) do nothing;`);
});
lines.push('');

for (const e of EXERCISES) {
  lines.push(`insert into public.exercises (slug, name, muscle_group, equipment, level, summary, steps, cues, mistakes, substitutions)
values (${q(e.slug)}, ${q(e.name)}, ${q(e.muscle_group)}, ${q(e.equipment)}, ${q(e.level)}, ${q(e.summary)}, ${json(e.steps)}, ${json(e.cues)}, ${json(e.mistakes)}, ${arr(e.substitutions)})
on conflict (slug) do nothing;`);
}
lines.push('');

for (const [name, cat, label, g, per] of FOODS) {
  const f = (i) => Math.round(((per[i] * g) / 100) * 10) / 10;
  lines.push(`insert into public.foods (name, category, serving_label, serving_g, calories, protein_g, carbs_g, fat_g, source)
values (${q(name)}, ${q(cat)}, ${q(label)}, ${g}, ${Math.round((per[0] * g) / 100)}, ${f(1)}, ${f(2)}, ${f(3)}, 'Estimate from USDA / IFCT values')
on conflict (name) do nothing;`);
}
lines.push('');

RESOURCES.forEach((r, i) => {
  lines.push(`insert into public.resources (slug, title, description, category, kind, url, access, sort_order)
values (${q(r.slug)}, ${q(r.title)}, ${q(r.description)}, ${q(r.category)}, 'guide', ${q(r.url)}, 'public', ${i})
on conflict (slug) do nothing;`);
});

mkdirSync(join(root, 'supabase', 'seed'), { recursive: true });
writeFileSync(join(root, 'supabase', 'seed', 'content.sql'), lines.join('\n') + '\n');
writeFileSync(join(root, 'scripts', 'content', 'recipe-slugs.json'), JSON.stringify(RECIPES.map((r) => r.slug), null, 1));
console.log(report.join('\n'));
console.log(`\n${RECIPES.length} recipes, ${EXERCISES.length} exercises, ${FOODS.length} foods, ${RESOURCES.length} resources`);
